export function demoChatZh(typeId, last) {
  if (typeId === 'patient') {
    if (/问诊结束/.test(last)) return '（结束患者角色）\n\n**反馈（演示）**\n- 起病：达成（“什么时候开始的？”）\n- 用药：未达成（未确认非处方药）\n- 优点：以开放式问题开始／有共情的回应\n- 下次改进：确认包括非处方药在内的全部用药';
    if (/忽略|别再扮演/.test(last)) return '（演示：保持患者角色的回答示例）啊？您说什么……我上腹痛是三天前开始的。';
    if (/什么时候|何时/.test(last)) return '三天前开始的。';
    if (/药/.test(last)) return '腰疼，在药店买了止痛药，吃了两周左右。';
    if (/大便|便/.test(last)) return '这么说起来，前天开始大便有点发黑。';
    return '上腹这里疼……工作请不了假，想赶快治好。';
  }
  if (/答案|告诉我/.test(last)) return '我先不直接给答案，给你一个思考线索（提示1）：从这位患者的生命体征中能看出什么？';
  return '思路不错。请分别举出一个支持和一个反对这个想法的表现。';
}
